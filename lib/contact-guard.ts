export function isFakeIndianMobile(phone10: string) {
  const digits = String(phone10 || "").replace(/\D/g, "");
  if (!/^[6-9]\d{9}$/.test(digits)) return true;
  if (/^(\d)\1{9}$/.test(digits)) return true;
  const ascending = "01234567890123456789";
  const descending = "98765432109876543210";
  if (ascending.includes(digits) || descending.includes(digits)) return true;
  const blocked = new Set([
    "9000000000",
    "8000000000",
    "7000000000",
    "6000000000",
    "9876543210",
    "9123456789",
    "9999999999",
    "8888888888",
    "7777777777",
    "6666666666",
    "9876543211",
    "9000000001",
  ]);
  if (blocked.has(digits)) return true;
  if (/^(\d)\1{4}(\d)\2{4}$/.test(digits)) return true;
  return false;
}

